def test_every_entry_has_its_driver_call_a_catalogue_block_and_a_rule6_case(table):
    catalogue = {u["key"]: u for u in json.loads(
        (ROOT / eut.CATALOGUE).read_text(encoding="utf-8"))["transaction_blocks"]["units"]}
    assert table["entries"]
    for e in (e for e in table["entries"] if e.get("basis") is None):  # S11 R-L3d-1: rules 1-3 entries; the block_exercise ones are pinned in test_s11_l3d_block_exercise.py
        assert e["atomic_unit"] in catalogue and e["block"] == "#" + e["atomic_unit"].rsplit("#", 1)[1], e
        assert e["cases"] and set(e["cases"]) <= set("abcd"), e
        path, _, line = e["driver_call"].rpartition(":")
        assert len((ROOT / path).read_text(encoding="utf-8").splitlines()) >= int(line) > 0, e
        assert catalogue[e["atomic_unit"]]["scope"].rsplit(".", 1)[-1] in (ROOT / path).read_text(encoding="utf-8").splitlines()[int(line) - 1]
    keys = [(e["family"], e["golden_unit"], e["atomic_unit"]) for e in table["entries"]]
    assert keys == sorted(set(keys))


def test_the_g1_resolutions_are_the_table_entries_on_rows_that_carry_the_pending_item(table, ledger):
    doc = json.loads((ROOT / "coverage/evidence-resolutions.json").read_text(encoding="utf-8"))
    g1 = [e for e in doc["resolutions"] if e["rule"] == "G1"]
    assert g1 == eut.g1_resolutions(table, ledger) and g1
    rows = {r["key"]: r for r in ledger["rows"]}
    for e in g1:
        assert rows[e["key"]]["kind"] == "atomic_unit" and eut.PENDING in rows[e["key"]]["evidence"]
        assert all(i.startswith("compare:effects.") for i in e["replaced_by"])
        for family in (i[len("compare:"):] for i in e["replaced_by"]):
            assert any(t["family"] == family and "atomic_unit:" + t["atomic_unit"] == e["key"] for t in table["entries"])
            assert f"{eut.G1_CITATION}{family}/" in e["citation"]
    # no other pending item was touched: the rows with no entry keep it
    resolved = {e["key"] for e in g1}
    left = [r for r in ledger["rows"] if r["kind"] == "atomic_unit" and eut.PENDING in r["verification"].get("unmet", [])]
    # S11 AU-REC-6a: _finish#1 was the last row to carry the item in its unmet list; with it joined none remains
    assert not left and not {r["key"] for r in left} & resolved
