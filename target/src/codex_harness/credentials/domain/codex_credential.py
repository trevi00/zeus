"""The non-secret shape and the secret leaves of a Codex file-store credential, and the fixed markers.

Layer: domain
Context: credentials
Owns: the pinned Codex CLI version/digest and the broker-generated `config.toml` (file store only), the
    credential bounds (`MAX_AUTH_BYTES`, `TOKEN_FIELDS`), `credential_shape` (keys, account identity and
    auth mode; a token value is only checked for presence), `credential_values` (every string credential
    leaf, in memory only), the redaction markers and JWT shapes, and `SETTLED_RUN_STATES` (the run-record
    states that prove a container gone, the one definition the execution cleanup ledger also reads)
Does not own: reading or writing any file (credentials.adapters), the container argv (execution)
Entry points: credential_shape, credential_values, CODEX_CONFIG, CODEX_CONFIG_SHA256, CODEX_CLI_VERSION,
    MAX_AUTH_BYTES, TOKEN_FIELDS, REDACTED, REDACTED_JWT, JWT_SHAPE, JWT_TAIL, NOT_CREDENTIAL, MIN_SECRET_CHARS,
    SETTLED_RUN_STATES
Contracts: INV-CODEX-CREDENTIAL-001

Moved from SOURCE M7 `adapters/role_containers` (the D3 v3 credential constants and the pure halves of
`credential_shape`/`credential_values`). RESEARCH-S3 R2: `cli_auth_credentials_store = "file"` is pinned
because `auto` would fall back between stores silently (CE-9); R4: refresh tokens are single use, which is
why the adapters admit one holder at a time.
"""

from __future__ import annotations

import hashlib
import json
import re

from codex_harness.kernel.errors import IsolationError

CODEX_CLI_VERSION = "0.156.1"
# sha256 of the npm @openai/codex@0.156.1 linux-x64 musl `codex` binary, checked by the image build.
CODEX_CLI_SHA256 = "0b2e9301d6100dddda3b9d5c80ebaeaa3a2f1962388f2f36f6b96a9f08b1f33f"
CODEX_EXECUTABLE = "/usr/local/bin/codex"
CODEX_HOME = "/codex-home"
CODEX_CONFIG = ('# zeus-codex-role-config-v1: generated by the Zeus broker, mounted read-only.\n'
                'cli_auth_credentials_store = "file"\n'
                'check_for_update_on_startup = false\n')
CODEX_CONFIG_SHA256 = hashlib.sha256(CODEX_CONFIG.encode("utf-8")).hexdigest()
MAX_AUTH_BYTES = 64 * 1024
TOKEN_FIELDS = ("id_token", "access_token", "refresh_token")
# The container run-record states that prove the container gone (execution's cleanup ledger RESOLVED).
SETTLED_RUN_STATES = ("removed", "refused")

REDACTED = "[REDACTED:codex-credential]"
REDACTED_JWT = "[REDACTED:jwt-shaped]"
# Defense in depth only: a JWT-shaped string (base64url header `{"...`, payload, signature).
JWT_SHAPE = re.compile(r"eyJ[A-Za-z0-9_-]{5,}\.[A-Za-z0-9_-]{5,}\.[A-Za-z0-9_-]*")
# A stream tail that may still grow into a JWT-shaped string with the next fragment (never starting
# inside a longer base64url/dotted run, so a completed JWT is not re-held from its payload).
JWT_TAIL = re.compile(r"(?<![A-Za-z0-9_.-])(?:e|ey|eyJ[A-Za-z0-9_-]*(?:\.[A-Za-z0-9_-]*){0,2})\Z")
# The auth.json leaves that are not credential material; every other string leaf is.
NOT_CREDENTIAL = ("auth_mode", "last_refresh")
MIN_SECRET_CHARS = 8  # a shorter leaf is no provider credential and would only corrupt ordinary text


def credential_shape(data: bytes) -> dict:
    """The non-secret structure of a Codex file-store credential: key sets, the account identity and
    the auth mode. A token value is only checked for presence, never returned."""
    try:
        body = json.loads(data.decode("utf-8"))
    except (UnicodeDecodeError, ValueError) as exc:
        raise IsolationError("credential_unparseable") from exc
    if not isinstance(body, dict) or not isinstance(body.get("tokens"), dict):
        raise IsolationError("credential_shape_invalid")
    tokens = body["tokens"]
    if not all(isinstance(tokens.get(name), str) and tokens[name] for name in TOKEN_FIELDS):
        raise IsolationError("credential_tokens_missing")
    if not isinstance(tokens.get("account_id"), str) or not tokens["account_id"]:
        raise IsolationError("credential_identity_missing")
    if body.get("OPENAI_API_KEY") not in (None, ""):
        # An API key is new billing, never authorized for product roles (D3 rejected alternatives).
        raise IsolationError("credential_api_key_refused")
    return {"keys": sorted(body), "token_keys": sorted(tokens), "account_id": tokens["account_id"],
            "auth_mode": body.get("auth_mode")}


def credential_values(data: bytes) -> set:
    """Every string-valued credential leaf (tokens, keys, identity) of a Codex auth.json, in memory only.
    A refusal names the check, never the content, and chains nothing that holds the bytes."""
    body = None
    try:
        body = json.loads(data.decode("utf-8"))
    except (UnicodeDecodeError, ValueError):
        pass
    if not isinstance(body, dict):
        raise IsolationError("credential_unparseable")
    values, stack = set(), [body]
    while stack:
        node = stack.pop()
        for key, value in (node.items() if isinstance(node, dict) else enumerate(node)):
            if isinstance(value, (dict, list)):
                stack.append(value)
            elif isinstance(value, str) and key not in NOT_CREDENTIAL and len(value) >= MIN_SECRET_CHARS:
                values.add(value)
    return values
